if not SECRET_KEY:
    if DEBUG:
        SECRET_KEY = "dev-inseguro-nao-use-em-producao"
    else:
        raise RuntimeError("Defina a variável de ambiente SECRET_KEY (ou DEBUG=True em desenvolvimento).")

